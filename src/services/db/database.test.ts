import 'fake-indexeddb/auto';
import { beforeEach, describe, expect, it } from 'vitest';
import type { Timer } from '../../domain/timer';
import type { TodoItem } from '../../features/todo/types';
import { base64ToBlob, blobToBase64, decodeBase64, encodeBase64 } from './base64';
import { getDatabase, __setDatabaseForTests } from './index';
import { IndexedDbDatabase } from './indexeddb';

function makeTimer(id: string, name: string): Timer {
  return {
    id,
    name,
    type: 'countdown',
    targetDate: '2030-01-01T00:00:00.000Z',
    timezone: 'UTC',
    color: '#0ea5e9',
    createdAt: '2026-01-01T00:00:00.000Z',
    isAutoGenerated: false,
  };
}

function makeTodo(id: string, text: string): TodoItem {
  return {
    id,
    text,
    completed: false,
    type: 'todo',
    createdAt: Date.now(),
  };
}

describe('数据库后端选择（Web 环境）', () => {
  beforeEach(() => {
    __setDatabaseForTests(null);
  });

  it('非 Tauri 环境注入 IndexedDB 后端', () => {
    expect(getDatabase().kind).toBe('indexeddb');
  });
});

describe('IndexedDB 后端', () => {
  const db = new IndexedDbDatabase();

  it('计时器写入后按写入顺序读回', async () => {
    const timers = [makeTimer('a', '一'), makeTimer('b', '二'), makeTimer('c', '三')];
    await db.writeTimers(timers);

    const stored = await db.readTimers();
    expect(stored.map((timer) => timer.id)).toEqual(['a', 'b', 'c']);
  });

  it('重排后的顺序会被持久化，且不泄漏内部排序字段', async () => {
    await db.writeTimers([makeTimer('c', '三'), makeTimer('a', '一')]);

    const stored = await db.readTimers();
    expect(stored.map((timer) => timer.id)).toEqual(['c', 'a']);
    expect(stored[0]).not.toHaveProperty('__order');
  });

  it('状态键值支持写入、读取与删除', async () => {
    await db.writeState('activeTimerId', 'a');
    expect(await db.readState('activeTimerId')).toBe('a');

    await db.writeState('activeTimerId', null);
    expect(await db.readState('activeTimerId')).toBeNull();
  });

  it('待办项按写入顺序读回', async () => {
    const items = [makeTodo('t2', '第二'), makeTodo('t1', '第一')];
    await db.writeTodoItems(items);

    const stored = await db.readTodoItems();
    expect(stored.map((item) => item.id)).toEqual(['t2', 't1']);
    expect(stored[1].text).toBe('第一');
  });

  it('背景图片可写入、读取与清空', async () => {
    const blob = new Blob(['timepulse'], { type: 'image/png' });
    await db.writeBackgroundImage({
      id: 'img_1',
      type: 'file',
      url: 'blob:mock',
      blob,
      metadata: {
        size: blob.size,
        mimeType: 'image/png',
        width: 10,
        height: 20,
        uploadedAt: '2026-01-01T00:00:00.000Z',
        name: 'wall.png',
      },
    });

    const stored = await db.readBackgroundImage('img_1');
    expect(stored?.id).toBe('img_1');
    expect(stored?.metadata.name).toBe('wall.png');
    // 注：fake-indexeddb 的结构化克隆会剥离 jsdom Blob 的原型，Blob 内容的往返由 SQLite/Base64 用例覆盖
    expect(await db.readBackgroundImages()).toHaveLength(1);

    await db.deleteBackgroundImage('img_1');
    expect(await db.readBackgroundImage('img_1')).toBeNull();

    await db.writeBackgroundImage({
      id: 'img_2',
      type: 'url',
      url: 'https://example.com/a.png',
      blob: blob,
      metadata: { size: blob.size, mimeType: 'image/png', width: 1, height: 1, uploadedAt: '2026-01-01T00:00:00.000Z' },
    });
    await db.clearBackgroundImages();
    expect(await db.readBackgroundImages()).toHaveLength(0);
  });
});

describe('Base64 编解码', () => {
  it('字节数组往返一致', () => {
    const bytes = new Uint8Array([0, 1, 2, 127, 128, 254, 255]);
    expect(Array.from(decodeBase64(encodeBase64(bytes)))).toEqual(Array.from(bytes));
  });

  it('Blob 往返一致', async () => {
    const blob = new Blob([new Uint8Array([9, 8, 7, 6])], { type: 'image/webp' });
    const base64 = await blobToBase64(blob);
    const restored = base64ToBlob(base64, 'image/webp');

    expect(restored.type).toBe('image/webp');
    expect(new Uint8Array(await restored.arrayBuffer())).toEqual(new Uint8Array([9, 8, 7, 6]));
  });
});
