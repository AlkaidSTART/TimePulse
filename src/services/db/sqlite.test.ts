import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => {
  const execute = vi.fn(async (_query: string, _values?: unknown[]) => ({ rowsAffected: 1, lastInsertId: 1 }));
  const select = vi.fn(async (_query: string, _values?: unknown[]) => [] as Array<Record<string, unknown>>);
  const load = vi.fn(async (_url: string) => ({ execute, select }));
  return { execute, select, load };
});

vi.mock('@tauri-apps/plugin-sql', () => ({ default: { load: mocks.load } }));

import { getDatabase, __setDatabaseForTests } from './index';
import { SQLITE_DATABASE_URL, SqliteDatabase, __resetSqliteConnectionForTests } from './sqlite';
import type { Timer } from '../../domain/timer';

type TauriWindow = Window & { __TAURI_INTERNALS__?: unknown };

function makeTimer(id: string, name: string): Timer {
  return {
    id,
    name,
    type: 'countdown',
    targetDate: '2030-01-01T00:00:00.000Z',
    timezone: 'UTC',
    color: '#0ea5e9',
    createdAt: '2026-01-01T00:00:00.000Z',
    isAutoGenerated: false,
  };
}

describe('SQLite 后端（Tauri 桌面端 / 移动端）', () => {
  beforeEach(() => {
    (window as TauriWindow).__TAURI_INTERNALS__ = {};
    __resetSqliteConnectionForTests();
    __setDatabaseForTests(null);
    mocks.execute.mockClear();
    mocks.select.mockClear();
    mocks.load.mockClear();
  });

  afterEach(() => {
    delete (window as TauriWindow).__TAURI_INTERNALS__;
  });

  it('Tauri 环境下选择 SQLite 后端并加载数据库文件', async () => {
    const db = getDatabase();
    expect(db.kind).toBe('sqlite');

    await db.init();
    expect(mocks.load).toHaveBeenCalledWith(SQLITE_DATABASE_URL);
  });

  it('写入计时器时按顺序 upsert 并清理已删除记录', async () => {
    const db = new SqliteDatabase();
    await db.writeTimers([makeTimer('a', '一'), makeTimer('b', '二')]);

    const [deleteQuery, deleteValues] = mocks.execute.mock.calls[0];
    expect(deleteQuery).toContain('DELETE FROM timers WHERE id NOT IN');
    expect(deleteValues).toEqual(['a', 'b']);

    const insertCalls = mocks.execute.mock.calls.slice(1);
    expect(insertCalls).toHaveLength(2);
    expect(insertCalls[0][0]).toContain('INSERT INTO timers');
    expect(insertCalls[0][0]).toContain('ON CONFLICT(id) DO UPDATE');
    expect(insertCalls[0][1]?.[0]).toBe('a');
    expect(JSON.parse(String(insertCalls[0][1]?.[1]))).toMatchObject({ id: 'a', name: '一' });
    expect(insertCalls[1][1]?.[2]).toBe(1);
  });

  it('写入空列表时直接清空表', async () => {
    const db = new SqliteDatabase();
    await db.writeTimers([]);

    expect(mocks.execute).toHaveBeenCalledTimes(1);
    expect(mocks.execute.mock.calls[0][0]).toBe('DELETE FROM timers');
  });

  it('读取计时器时按 sort_order 查询并跳过损坏数据', async () => {
    mocks.select.mockResolvedValueOnce([
      { data: JSON.stringify(makeTimer('a', '一')) },
      { data: '{ 损坏的 JSON' },
      { data: JSON.stringify(makeTimer('b', '二')) },
    ]);

    const db = new SqliteDatabase();
    const timers = await db.readTimers();

    expect(mocks.select.mock.calls[0][0]).toContain('ORDER BY sort_order ASC');
    expect(timers.map((timer) => timer.id)).toEqual(['a', 'b']);
  });

  it('待办项写入与读取走 todo_items 表', async () => {
    const db = new SqliteDatabase();
    await db.writeTodoItems([{ id: 't1', text: '写代码', completed: false, type: 'todo', createdAt: 1 }]);

    expect(mocks.execute.mock.calls[0][0]).toContain('DELETE FROM todo_items');
    expect(mocks.execute.mock.calls[1][0]).toContain('INSERT INTO todo_items');

    mocks.select.mockResolvedValueOnce([{ data: JSON.stringify({ id: 't1', text: '写代码', completed: false, type: 'todo', createdAt: 1 }) }]);
    expect(await db.readTodoItems()).toHaveLength(1);
  });

  it('状态键值按 JSON 序列化读写，写入 null 表示删除', async () => {
    const db = new SqliteDatabase();
    await db.writeState('activeTimerId', 'a');
    expect(mocks.execute.mock.calls[0][0]).toContain('INSERT INTO app_state');
    expect(mocks.execute.mock.calls[0][1]).toEqual(['activeTimerId', '"a"', expect.any(String)]);

    mocks.select.mockResolvedValueOnce([{ value: '"a"' }]);
    expect(await db.readState('activeTimerId')).toBe('a');

    await db.writeState('activeTimerId', null);
    expect(mocks.execute.mock.calls[1][0]).toBe('DELETE FROM app_state WHERE key = $1');
  });

  it('背景图片以 Base64 写入并可还原为 Blob', async () => {
    const db = new SqliteDatabase();
    const blob = new Blob([new Uint8Array([1, 2, 3, 255])], { type: 'image/png' });

    await db.writeBackgroundImage({
      id: 'img_1',
      type: 'file',
      url: 'blob:mock',
      blob,
      metadata: {
        size: blob.size,
        mimeType: 'image/png',
        width: 4,
        height: 4,
        uploadedAt: '2026-01-01T00:00:00.000Z',
        name: 'wall.png',
      },
    });

    const insertCall = mocks.execute.mock.calls.at(-1);
    expect(insertCall?.[0]).toContain('INSERT INTO custom_backgrounds');
    const values = insertCall?.[1] ?? [];
    expect(values[0]).toBe('img_1');
    expect(values[7]).toBe('wall.png');
    const base64 = String(values[9]);
    expect(Array.from(atob(base64), (char) => char.charCodeAt(0))).toEqual([1, 2, 3, 255]);

    mocks.select.mockResolvedValueOnce([
      {
        id: 'img_1',
        type: 'file',
        url: 'blob:mock',
        mime_type: 'image/png',
        size: 4,
        width: 4,
        height: 4,
        name: 'wall.png',
        uploaded_at: '2026-01-01T00:00:00.000Z',
        blob_base64: base64,
      },
    ]);

    const stored = await db.readBackgroundImage('img_1');
    expect(stored?.metadata.name).toBe('wall.png');
    expect(stored?.blob.type).toBe('image/png');
    expect(new Uint8Array(await stored!.blob.arrayBuffer())).toEqual(new Uint8Array([1, 2, 3, 255]));
  });
});
