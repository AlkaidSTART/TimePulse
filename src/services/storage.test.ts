import 'fake-indexeddb/auto';
import { describe, expect, it } from 'vitest';
import {
  readActiveTimerId,
  readCachedActiveTimerId,
  readCachedTimers,
  readTimers,
  writeActiveTimerId,
  writeTimers,
} from './storage';
import type { Timer } from '../domain/timer';

function makeTimer(id: string, name: string): Timer {
  return {
    id,
    name,
    type: 'countdown',
    targetDate: '2030-01-01T00:00:00.000Z',
    timezone: 'UTC',
    color: '#0ea5e9',
    createdAt: '2026-01-01T00:00:00.000Z',
    isAutoGenerated: false,
  };
}

// 说明：本文件测试共享同一个 TimePulseDB（模块级连接缓存），
// 迁移用例依赖“数据库为空”的初始状态，因此必须保持文件内顺序靠前。
describe('storage: IndexedDB 计时器存储', () => {
  it('首次读取时把旧版 localStorage 数据迁移进 IndexedDB', async () => {
    const legacyTimer = makeTimer('legacy-1', '旧版计时器');
    localStorage.setItem('timers', JSON.stringify([legacyTimer]));
    localStorage.setItem('activeTimerId', 'legacy-1');

    const timers = await readTimers();
    expect(timers).toHaveLength(1);
    expect(timers[0]).toMatchObject({ id: 'legacy-1', name: '旧版计时器' });

    const activeId = await readActiveTimerId();
    expect(activeId).toBe('legacy-1');
  });

  it('写入后可从 IndexedDB 读回，并留下 localStorage 降级备份', async () => {
    const first = makeTimer('idb-1', '计时器一');
    const second = makeTimer('idb-2', '计时器二');

    await writeTimers([first, second]);
    const timers = await readTimers();

    expect(timers.map((timer) => timer.id).sort()).toEqual(['idb-1', 'idb-2']);
    expect(timers.find((timer) => timer.id === 'idb-2')?.name).toBe('计时器二');

    const backup = JSON.parse(localStorage.getItem('timers') ?? '[]') as Timer[];
    expect(backup).toHaveLength(2);
  });

  it('活动计时器 ID 可写可读并同步到 localStorage 备份', async () => {
    await writeActiveTimerId('idb-2');
    expect(await readActiveTimerId()).toBe('idb-2');
    expect(localStorage.getItem('activeTimerId')).toBe('idb-2');

    await writeActiveTimerId(null);
    expect(await readActiveTimerId()).toBeNull();
    expect(localStorage.getItem('activeTimerId')).toBeNull();
  });

  it('当 localStorage 不可用或传入 null 时安全降级且不抛出异常', () => {
    expect(readCachedTimers(null)).toEqual([]);
    expect(readCachedActiveTimerId(null)).toBeNull();
  });
});
