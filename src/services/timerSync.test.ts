import 'fake-indexeddb/auto';
import { describe, it, expect, beforeEach, afterEach, vi } from 'vitest';
import { supabase } from '@/lib/supabase';
import { useAuthStore } from '@/stores/useAuthStore';
import { useTimerStore } from '@/stores/useTimerStore';
import type { Timer } from '@/domain/timer';
import {
  getClientDeviceId,
  setClientDeviceIdForTest,
  isApplyingRemoteSync,
  applyRemoteTimers,
  pushTimersToCloud,
  pullTimersFromCloud,
  schedulePushToCloud,
  flushPushToCloud,
  setupRealtimeChannel,
  teardownRealtimeChannel,
  notifyLocalTimerChange,
  reconcileCloudOnLogin,
} from './timerSync';

function makeCountdown(id: string, name: string): Timer {
  return {
    id,
    name,
    type: 'countdown',
    targetDate: '2030-01-01T00:00:00.000Z',
    timezone: 'UTC',
    color: '#0ea5e9',
    createdAt: '2026-01-01T00:00:00.000Z',
    isAutoGenerated: false,
  };
}

function makeStopwatch(id: string, name: string, isRunning = false): Timer {
  return {
    id,
    name,
    type: 'stopwatch',
    color: '#10b981',
    createdAt: '2026-01-01T00:00:00.000Z',
    startTime: '2026-01-01T00:00:00.000Z',
    isRunning,
    pausedAt: null,
    totalPausedTime: 0,
    laps: [],
  };
}

describe('TimerSync Service - 多端计时器同步', () => {
  beforeEach(() => {
    localStorage.clear();
    sessionStorage.clear();
    setClientDeviceIdForTest(null);
    teardownRealtimeChannel();
    useAuthStore.setState({ user: null, session: null });
    vi.restoreAllMocks();
  });

  afterEach(() => {
    teardownRealtimeChannel();
    vi.restoreAllMocks();
  });

  describe('Device ID 管理', () => {
    it('为当前客户端生成稳定的 deviceId', () => {
      const id1 = getClientDeviceId();
      const id2 = getClientDeviceId();
      expect(id1).toBeTruthy();
      expect(id1).toBe(id2);
      expect(id1.startsWith('dev_')).toBe(true);
    });

    it('允许为测试显式指定 deviceId', () => {
      setClientDeviceIdForTest('test-device-pc');
      expect(getClientDeviceId()).toBe('test-device-pc');
    });
  });

  describe('云端数据推送 (pushTimersToCloud)', () => {
    it('未登录时直接跳过推送并返回 false', async () => {
      const result = await pushTimersToCloud([makeCountdown('t1', '倒计时')], 't1');
      expect(result).toBe(false);
    });

    it('已登录时将计时器与活动 ID 上传至 Supabase timers 与 app_state', async () => {
      useAuthStore.setState({
        user: { id: 'user-123' } as unknown as any,
      });

      const upsertTimersSpy = vi.fn().mockResolvedValue({ error: null });
      const deleteTimersSpy = vi.fn().mockReturnValue({
        eq: vi.fn().mockReturnValue({
          not: vi.fn().mockResolvedValue({ error: null }),
        }),
      });
      const upsertStateSpy = vi.fn().mockResolvedValue({ error: null });

      vi.spyOn(supabase, 'from').mockImplementation((table: string) => {
        if (table === 'timers') {
          return {
            upsert: upsertTimersSpy,
            delete: deleteTimersSpy,
          } as unknown as any;
        }
        if (table === 'app_state') {
          return {
            upsert: upsertStateSpy,
          } as unknown as any;
        }
        return {} as unknown as any;
      });

      const timer1 = makeCountdown('t1', '工作番茄钟');
      const timer2 = makeStopwatch('t2', '锻炼秒表', true);

      const result = await pushTimersToCloud([timer1, timer2], 't2');
      expect(result).toBe(true);

      expect(upsertTimersSpy).toHaveBeenCalledTimes(1);
      const rows = upsertTimersSpy.mock.calls[0][0];
      expect(rows).toHaveLength(2);
      expect(rows[0]).toMatchObject({
        user_id: 'user-123',
        id: 't1',
        sort_order: 0,
      });
      expect(rows[1]).toMatchObject({
        user_id: 'user-123',
        id: 't2',
        sort_order: 1,
      });

      expect(upsertStateSpy).toHaveBeenCalledWith(
        expect.objectContaining({
          user_id: 'user-123',
          key: 'activeTimerId',
          value: { activeTimerId: 't2' },
        }),
        { onConflict: 'user_id,key' },
      );
    });
  });

  describe('云端数据拉取 (pullTimersFromCloud)', () => {
    it('未登录时返回 null', async () => {
      const data = await pullTimersFromCloud();
      expect(data).toBeNull();
    });

    it('成功拉取并解析云端计时器及活动 ID', async () => {
      useAuthStore.setState({
        user: { id: 'user-123' } as unknown as any,
      });

      const mockTimers = [
        {
          id: 'cloud-1',
          data: makeCountdown('cloud-1', '云端倒计时'),
          sort_order: 0,
        },
      ];

      vi.spyOn(supabase, 'from').mockImplementation((table: string) => {
        if (table === 'timers') {
          return {
            select: vi.fn().mockReturnValue({
              eq: vi.fn().mockReturnValue({
                order: vi.fn().mockResolvedValue({ data: mockTimers, error: null }),
              }),
            }),
          } as unknown as any;
        }
        if (table === 'app_state') {
          return {
            select: vi.fn().mockReturnValue({
              eq: vi.fn().mockReturnValue({
                eq: vi.fn().mockReturnValue({
                  maybeSingle: vi.fn().mockResolvedValue({
                    data: { value: { activeTimerId: 'cloud-1' } },
                    error: null,
                  }),
                }),
              }),
            }),
          } as unknown as any;
        }
        return {} as unknown as any;
      });

      const cloudData = await pullTimersFromCloud();
      expect(cloudData).not.toBeNull();
      expect(cloudData?.timers).toHaveLength(1);
      expect(cloudData?.timers[0].name).toBe('云端倒计时');
      expect(cloudData?.activeTimerId).toBe('cloud-1');
    });
  });

  describe('远程更新应用 (applyRemoteTimers)', () => {
    it('应用远程计时器并更新 useTimerStore', () => {
      const remoteTimer = makeCountdown('remote-1', '手机创建的倒计时');

      expect(isApplyingRemoteSync()).toBe(false);
      applyRemoteTimers([remoteTimer], 'remote-1');
      expect(isApplyingRemoteSync()).toBe(false);

      const store = useTimerStore.getState();
      expect(store.timers.some((t) => t.id === 'remote-1')).toBe(true);
      expect(store.activeTimerId).toBe('remote-1');
    });
  });

  describe('实时多端通道 (setupRealtimeChannel)', () => {
    it('订阅用户专属广播通道，并正确处理来自对端的广播', () => {
      setClientDeviceIdForTest('my-computer');
      const userId = 'user-abc';

      let broadcastHandler: ((msg: { payload: any }) => void) | null = null;
      const mockChannel = {
        on: vi.fn().mockImplementation((_event, _filter, callback) => {
          broadcastHandler = callback;
          return mockChannel;
        }),
        subscribe: vi.fn().mockImplementation((callback) => {
          callback('SUBSCRIBED');
          return mockChannel;
        }),
        unsubscribe: vi.fn().mockResolvedValue('ok'),
        send: vi.fn().mockResolvedValue('ok'),
      };

      vi.spyOn(supabase, 'channel').mockReturnValue(mockChannel as unknown as any);

      setupRealtimeChannel(userId);

      expect(supabase.channel).toHaveBeenCalledWith(
        `timepulse:sync:${userId}`,
        expect.objectContaining({
          config: { broadcast: { self: false } },
        }),
      );
      expect(mockChannel.subscribe).toHaveBeenCalled();
      expect(broadcastHandler).not.toBeNull();

      // 1. 模拟收到来自本机的广播（回环测试）：应被忽略
      const localStoreBefore = useTimerStore.getState();
      broadcastHandler!({
        payload: {
          originDeviceId: 'my-computer',
          userId,
          timestamp: Date.now(),
          timers: [makeCountdown('ignored-1', '不应被应用的计时器')],
          activeTimerId: 'ignored-1',
        },
      });
      expect(useTimerStore.getState().timers).toEqual(localStoreBefore.timers);

      // 2. 模拟收到来自对端（如手机端）的广播：应当立即同步应用
      const phoneTimer = makeStopwatch('phone-sw-1', '手机开启的正向计时', true);
      broadcastHandler!({
        payload: {
          originDeviceId: 'phone-device-mobile',
          userId,
          timestamp: Date.now(),
          timers: [phoneTimer],
          activeTimerId: 'phone-sw-1',
        },
      });

      const storeAfter = useTimerStore.getState();
      expect(storeAfter.timers).toHaveLength(1);
      expect(storeAfter.timers[0].name).toBe('手机开启的正向计时');
      expect((storeAfter.timers[0] as any).isRunning).toBe(true);
      expect(storeAfter.activeTimerId).toBe('phone-sw-1');
    });
  });

  describe('本地变更广播 (notifyLocalTimerChange)', () => {
    it('已登录时发送 Realtime 广播并触发防抖云端推送', async () => {
      setClientDeviceIdForTest('my-phone');
      useAuthStore.setState({
        user: { id: 'user-abc' } as unknown as any,
      });

      const sendSpy = vi.fn().mockResolvedValue('ok');
      const mockChannel = {
        on: vi.fn().mockReturnThis(),
        subscribe: vi.fn().mockReturnThis(),
        unsubscribe: vi.fn().mockResolvedValue('ok'),
        send: sendSpy,
      };
      vi.spyOn(supabase, 'channel').mockReturnValue(mockChannel as unknown as any);

      setupRealtimeChannel('user-abc');

      const timer = makeStopwatch('sw-test', '测试秒表', true);
      notifyLocalTimerChange([timer], 'sw-test', { type: 'update', timer });

      expect(sendSpy).toHaveBeenCalledTimes(1);
      expect(sendSpy).toHaveBeenCalledWith(
        expect.objectContaining({
          type: 'broadcast',
          event: 'timer_sync',
          payload: expect.objectContaining({
            originDeviceId: 'my-phone',
            userId: 'user-abc',
            actionType: 'update',
            activeTimerId: 'sw-test',
          }),
        }),
      );
    });
  });

  describe('登录数据协调 (reconcileCloudOnLogin)', () => {
    it('若云端已有计时器，且本地有离线新增的计时器，自动合并并推送', async () => {
      useAuthStore.setState({
        user: { id: 'user-sync' } as unknown as any,
      });

      const localOfflineTimer = makeCountdown('offline-1', '离线创建的计时器');
      useTimerStore.setState({
        timers: [localOfflineTimer],
        activeTimerId: 'offline-1',
        isLoaded: true,
      });

      const cloudTimer = makeCountdown('cloud-1', '云端已有计时器');
      const upsertSpy = vi.fn().mockResolvedValue({ error: null });

      vi.spyOn(supabase, 'from').mockImplementation((table: string) => {
        if (table === 'timers') {
          return {
            select: vi.fn().mockReturnValue({
              eq: vi.fn().mockReturnValue({
                order: vi.fn().mockResolvedValue({
                  data: [{ id: 'cloud-1', data: cloudTimer, sort_order: 0 }],
                  error: null,
                }),
              }),
            }),
            upsert: upsertSpy,
            delete: vi.fn().mockReturnValue({
              eq: vi.fn().mockReturnValue({
                not: vi.fn().mockResolvedValue({ error: null }),
              }),
            }),
          } as unknown as any;
        }
        if (table === 'app_state') {
          return {
            select: vi.fn().mockReturnValue({
              eq: vi.fn().mockReturnValue({
                eq: vi.fn().mockReturnValue({
                  maybeSingle: vi.fn().mockResolvedValue({
                    data: { value: { activeTimerId: 'cloud-1' } },
                    error: null,
                  }),
                }),
              }),
            }),
            upsert: vi.fn().mockResolvedValue({ error: null }),
          } as unknown as any;
        }
        return {} as unknown as any;
      });

      await reconcileCloudOnLogin('user-sync');

      const currentTimers = useTimerStore.getState().timers;
      expect(currentTimers.some((t) => t.id === 'cloud-1')).toBe(true);
      expect(currentTimers.some((t) => t.id === 'offline-1')).toBe(true);
      expect(upsertSpy).toHaveBeenCalled();
    });
  });
});
