import { useMemo } from 'react';
import { create } from 'zustand';
import { v4 as uuidv4 } from 'uuid';
import { getHolidaysList } from '@/domain/holidays';
import {
  getTimerType,
  parseTimer,
  type Holiday,
  type Timer,
  type TimerType,
  type TimeValue,
} from '@/domain/timer';
import { normalizeLanguage } from '@/i18n/types';
import { timerReducer, type TimerAction } from '@/features/timer-management/reducer';
import { addNotification, removeNotification } from '@/services/notificationManager';
import {
  readActiveTimerId,
  readCachedActiveTimerId,
  readCachedTimers,
  readTimers,
  scheduleTimersWrite,
  writeActiveTimerId,
} from '@/services/storage';
import { useThemeStore } from './useThemeStore';

export type TimerInput = {
  id?: string;
  name: string;
  type?: TimerType;
  targetDate?: TimeValue;
  timezone?: string;
  startTime?: TimeValue | null;
  isRunning?: boolean;
  pausedAt?: TimeValue | null;
  totalPausedTime?: number;
  laps?: unknown[];
  color?: string;
  createdAt?: string;
  isAutoGenerated?: boolean;
  [key: string]: unknown;
};

export type TimerUpdate = Partial<Timer> & Record<string, unknown>;

export interface TimerState {
  timers: Timer[];
  activeTimerId: string | null;
  holidaysList: Holiday[];
  isLoaded: boolean;

  setActiveTimerId: (id: string | null) => void;
  reorderTimers: (orderedIds: string[]) => void;
  addTimer: (timerData: TimerInput) => string;
  deleteTimer: (id: string) => void;
  updateTimer: (id: string, updatedData: TimerUpdate) => void;
  renameStopwatchLap: (timerId: string, lapIndex: number, name: string) => void;
  deleteStopwatchLap: (timerId: string, lapIndex: number) => void;
  getActiveTimer: () => Timer | null;
  initTimers: () => Promise<void>;
  dispatch: (action: TimerAction) => void;
}

export function getDefaultTimer(): Timer {
  const timezone = typeof Intl !== 'undefined' && Intl.DateTimeFormat().resolvedOptions().timeZone
    ? Intl.DateTimeFormat().resolvedOptions().timeZone
    : 'UTC';
  const language = normalizeLanguage(
    typeof window === 'undefined' ? null : new URLSearchParams(window.location.search).get('lang'),
  );
  const localLabel = language === 'en-US' ? 'Local' : '本地';
  return {
    id: 'default',
    name: language === 'en-US' ? 'Local Time' : '本地时间',
    type: 'worldclock',
    timezone,
    city: localLabel,
    country: localLabel,
    color: '#0EA5E9',
    createdAt: new Date().toISOString(),
    isAutoGenerated: true,
  };
}

function isCountdown(timer: Timer): boolean {
  return getTimerType(timer) === 'countdown';
}

function toNotification(timer: Timer): { id: string; title: string; targetTime: number } | null {
  if (!isCountdown(timer) || !('targetDate' in timer)) return null;
  const targetDate = (timer as Timer & { targetDate: TimeValue }).targetDate;
  const targetTime = targetDate instanceof Date
    ? targetDate.getTime()
    : typeof targetDate === 'number'
      ? targetDate
      : new Date(targetDate).getTime();
  return { id: timer.id, title: timer.name, targetTime };
}

function parseTimerInput(timerData: TimerInput): Timer {
  const parsed = parseTimer({
    ...timerData,
    id: timerData.id || uuidv4(),
    createdAt: timerData.createdAt || new Date().toISOString(),
    isAutoGenerated: timerData.isAutoGenerated === true,
    type: timerData.type || 'countdown',
  });
  if (!parsed) throw new Error('计时器数据格式错误');
  return parsed;
}

function syncActiveTimerColor(timers: Timer[], activeTimerId: string | null): void {
  if (!activeTimerId) return;
  const activeTimer = timers.find((t) => t.id === activeTimerId);
  if (activeTimer?.color) {
    const themeStore = useThemeStore.getState();
    if (themeStore.accentColor !== activeTimer.color) {
      themeStore.updateAccentColor(activeTimer.color);
    }
  }
}

function getInitialTimerState(): { timers: Timer[]; activeTimerId: string | null } {
  if (typeof window === 'undefined') {
    return { timers: [], activeTimerId: null };
  }
  const cachedTimers = readCachedTimers();
  const cachedActiveId = readCachedActiveTimerId();

  if (cachedTimers.length > 0) {
    const selectedId = cachedActiveId && cachedTimers.some((t) => t.id === cachedActiveId)
      ? cachedActiveId
      : cachedTimers[0].id;
    return { timers: cachedTimers, activeTimerId: selectedId };
  }

  // 首屏无缓存时提供默认本地时钟，消除首屏等待
  const defaultTimer = getDefaultTimer();
  return { timers: [defaultTimer], activeTimerId: defaultTimer.id };
}

const initialTimerState = getInitialTimerState();

export const useTimerStore = create<TimerState>((set, get) => ({
  timers: initialTimerState.timers,
  activeTimerId: initialTimerState.activeTimerId,
  holidaysList: typeof window !== 'undefined' ? getHolidaysList() : [],
  isLoaded: false,

  dispatch: (action: TimerAction) => {
    set((state) => {
      const next = timerReducer({ timers: state.timers, activeTimerId: state.activeTimerId }, action);
      if (state.isLoaded) {
        if (next.timers !== state.timers && next.timers.length > 0) {
          scheduleTimersWrite(next.timers);
        }
        if (next.activeTimerId !== state.activeTimerId && next.activeTimerId) {
          void writeActiveTimerId(next.activeTimerId);
        }
      }
      syncActiveTimerColor(next.timers, next.activeTimerId);
      return next;
    });
  },

  setActiveTimerId: (id: string | null) => {
    if (id) {
      get().dispatch({ type: 'select', id });
    }
  },

  reorderTimers: (orderedIds: string[]) => {
    get().dispatch({ type: 'reorder', ids: orderedIds });
  },

  addTimer: (timerData: TimerInput): string => {
    const newTimer = parseTimerInput(timerData);
    get().dispatch({ type: 'upsert', timer: newTimer });
    const notification = toNotification(newTimer);
    if (notification) {
      void addNotification(notification).catch((error: unknown) => console.log('设置通知失败:', error));
    }
    console.log(`${new Date().toLocaleTimeString()} | [计时器管理] 已添加计时器: ${newTimer.name} (${getTimerType(newTimer)})`);
    return newTimer.id;
  },

  deleteTimer: (id: string) => {
    removeNotification(id);
    const { timers, dispatch } = get();
    const remaining = timers.filter((timer) => timer.id !== id);
    const replacement = remaining.length === 0 ? getDefaultTimer() : undefined;
    dispatch({ type: 'remove', id, replacement });
    console.log(`${new Date().toLocaleTimeString()} | [计时器管理] 已删除计时器ID: ${id}`);
  },

  updateTimer: (id: string, updatedData: TimerUpdate) => {
    const { timers, dispatch } = get();
    const current = timers.find((timer) => timer.id === id);
    if (!current) return;
    const updatedTimer = parseTimer({ ...current, ...updatedData, id });
    if (!updatedTimer) return;
    dispatch({ type: 'update', timer: updatedTimer });
    const notification = toNotification(updatedTimer);
    if (notification) {
      void addNotification(notification).catch((error: unknown) => console.log('更新通知失败:', error));
    }
    console.log(`${new Date().toLocaleTimeString()} | [计时器管理] 已更新计时器ID: ${id}`);
  },

  renameStopwatchLap: (timerId: string, lapIndex: number, name: string) => {
    get().dispatch({ type: 'renameStopwatchLap', timerId, lapIndex, name });
  },

  deleteStopwatchLap: (timerId: string, lapIndex: number) => {
    get().dispatch({ type: 'deleteStopwatchLap', timerId, lapIndex });
  },

  getActiveTimer: () => {
    const { timers, activeTimerId } = get();
    return timers.find((timer) => timer.id === activeTimerId) ?? null;
  },

  initTimers: async () => {
    console.log(`${new Date().toLocaleTimeString()} | [初始化] 开始加载计时器数据`);
    const [loadedTimers, savedActiveTimerId] = await Promise.all([readTimers(), readActiveTimerId()]);

    let targetTimers: Timer[] = [];
    let selectedId: string | null = null;

    if (loadedTimers.length === 0) {
      const defaultTimer = getDefaultTimer();
      targetTimers = [defaultTimer];
      selectedId = defaultTimer.id;
      console.log(`${new Date().toLocaleTimeString()} | [初始化] 没有本地计时器，创建默认计时器`);
    } else {
      const language = normalizeLanguage(
        typeof window === 'undefined' ? null : new URLSearchParams(window.location.search).get('lang'),
      );
      const migrated = loadedTimers.map((timer) => {
        let current = timer;
        if (
          current.name === '本地 - Asia/Shanghai' ||
          current.name === 'Local - Asia/Shanghai' ||
          (current.id === 'default' && (current.name.includes('Asia/Shanghai') || current.name === '本地 - ' + current.timezone))
        ) {
          current = {
            ...current,
            name: language === 'en-US' ? 'Local Time' : '本地时间',
          };
        }
        return current.id === 'default' && current.isAutoGenerated === true && getTimerType(current) !== 'worldclock'
          ? getDefaultTimer()
          : current;
      });
      selectedId = savedActiveTimerId && migrated.some((timer) => timer.id === savedActiveTimerId)
        ? savedActiveTimerId
        : migrated[0].id;
      targetTimers = migrated;
      console.log(`${new Date().toLocaleTimeString()} | [初始化] 恢复活动计时器: ${selectedId}`);
    }

    set({
      timers: targetTimers,
      activeTimerId: selectedId,
      holidaysList: getHolidaysList(),
      isLoaded: true,
    });

    syncActiveTimerColor(targetTimers, selectedId);
    console.log(`${new Date().toLocaleTimeString()} | [初始化] 本地数据加载完成，共${targetTimers.length}个计时器`);
  },
}));

// 浏览器环境中自动触发初始化
if (typeof window !== 'undefined') {
  void useTimerStore.getState().initTimers();
}

/**
 * 兼容原有 Context 的 hook
 */
export function useTimers() {
  const timers = useTimerStore((s) => s.timers);
  const activeTimerId = useTimerStore((s) => s.activeTimerId);
  const holidaysList = useTimerStore((s) => s.holidaysList);
  const setActiveTimerId = useTimerStore((s) => s.setActiveTimerId);
  const reorderTimers = useTimerStore((s) => s.reorderTimers);
  const addTimer = useTimerStore((s) => s.addTimer);
  const deleteTimer = useTimerStore((s) => s.deleteTimer);
  const updateTimer = useTimerStore((s) => s.updateTimer);
  const renameStopwatchLap = useTimerStore((s) => s.renameStopwatchLap);
  const deleteStopwatchLap = useTimerStore((s) => s.deleteStopwatchLap);
  const getActiveTimer = useTimerStore((s) => s.getActiveTimer);

  return useMemo(() => ({
    timers,
    activeTimerId,
    setActiveTimerId,
    reorderTimers,
    addTimer,
    deleteTimer,
    updateTimer,
    renameStopwatchLap,
    deleteStopwatchLap,
    getActiveTimer,
    holidaysList,
  }), [
    timers,
    activeTimerId,
    setActiveTimerId,
    reorderTimers,
    addTimer,
    deleteTimer,
    updateTimer,
    renameStopwatchLap,
    deleteStopwatchLap,
    getActiveTimer,
    holidaysList,
  ]);
}
