import { test, expect } from '@playwright/test';

test.describe('Generate README screenshots', () => {
  test.use({
    viewport: { width: 1280, height: 800 },
    deviceScaleFactor: 2,
    colorScheme: 'light',
  });

  test('capture all showcase screenshots', async ({ page, context }) => {
    // 1. Initial page load (Cheer / Time Greeting)
    await page.goto('/', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    // Cheer Page screenshot
    await page.screenshot({
      path: 'docs/screenshots/01-cheer-greeting.png',
      fullPage: false,
    });

    // 2. Add sample timers if not already present, then navigate to main timer view
    await page.evaluate(() => {
      // Clear out old timers and seed representative timers
      const now = new Date();
      const nextYear = now.getFullYear() + 1;
      const newYearTarget = new Date(`${nextYear}-01-01T00:00:00`).toISOString();

      const sampleTimers = [
        {
          id: 'demo-countdown',
          name: `${nextYear} 元旦跨年倒计时`,
          type: 'countdown',
          targetDate: newYearTarget,
          targetTime: '00:00',
          color: '#3B82F6',
          createdAt: now.toISOString(),
          isAutoGenerated: false,
        },
        {
          id: 'demo-pomodoro',
          name: '深度专注番茄钟',
          type: 'countdown',
          countdownType: 'short',
          durationSeconds: 1500,
          shortHours: 0,
          shortMinutes: 25,
          shortSeconds: 0,
          targetDate: new Date(now.getTime() + 25 * 60 * 1000).toISOString(),
          color: '#10B981',
          createdAt: now.toISOString(),
          isAutoGenerated: false,
        },
        {
          id: 'demo-tokyo',
          name: '东京时间',
          type: 'worldclock',
          timezone: 'Asia/Tokyo',
          city: '东京',
          country: '日本',
          color: '#EC4899',
          createdAt: now.toISOString(),
          isAutoGenerated: false,
        },
      ];

      localStorage.setItem('timepulse_timers', JSON.stringify(sampleTimers));
      localStorage.setItem('timepulse_active_timer_id', 'demo-countdown');
    });

    // Navigate to Main Timer View
    await page.goto('/#main', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    await page.screenshot({
      path: 'docs/screenshots/02-timer-countdown.png',
      fullPage: false,
    });

    // Switch to Short Pomodoro Timer
    await page.evaluate(() => {
      localStorage.setItem('timepulse_active_timer_id', 'demo-pomodoro');
    });
    await page.goto('/#main', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    await page.screenshot({
      path: 'docs/screenshots/03-timer-short-focus.png',
      fullPage: false,
    });

    // 3. Todo Page
    await page.evaluate(() => {
      const sampleTodos = [
        {
          id: 'todo-1',
          text: '完成 TimePulse 现代化架构与多端适配文档',
          completed: false,
          priority: 'high',
          color: '#EF4444',
          createdAt: Date.now(),
        },
        {
          id: 'todo-2',
          text: '保持 25 分钟番茄钟深度工作',
          completed: false,
          priority: 'medium',
          color: '#F59E0B',
          createdAt: Date.now() - 3600000,
        },
        {
          id: 'todo-3',
          text: '整理桌面与今日灵感摘录',
          completed: true,
          priority: 'low',
          color: '#10B981',
          createdAt: Date.now() - 7200000,
        },
      ];
      localStorage.setItem('timepulse_todos', JSON.stringify(sampleTodos));
    });

    await page.goto('/#todo', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    await page.screenshot({
      path: 'docs/screenshots/04-todo-page.png',
      fullPage: false,
    });

    // 4. Personal Settings Page
    await page.goto('/#settings', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    await page.screenshot({
      path: 'docs/screenshots/05-personal-settings.png',
      fullPage: false,
    });

    // 5. Timer Type Modal (Add Timer)
    await page.goto('/#main', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1000);
    const addBtn = page.locator('[data-insightflare-event="timer_create_open"]').first();
    if (await addBtn.isVisible()) {
      await addBtn.click();
      await page.waitForTimeout(1000);
      await page.screenshot({
        path: 'docs/screenshots/06-modal-add-timer.png',
        fullPage: false,
      });
      // Close modal
      await page.keyboard.press('Escape');
      await page.waitForTimeout(500);
    }

    // 6. Background Settings Modal
    const bgBtn = page.locator('[data-insightflare-event="background_open"]').first();
    if (await bgBtn.isVisible()) {
      await bgBtn.click();
      await page.waitForTimeout(1000);
      await page.screenshot({
        path: 'docs/screenshots/07-modal-background.png',
        fullPage: false,
      });
      await page.keyboard.press('Escape');
      await page.waitForTimeout(500);
    }

    // 7. Share Modal
    const shareBtn = page.locator('[data-insightflare-event="share_open"]').first();
    if (await shareBtn.isVisible()) {
      await shareBtn.click();
      await page.waitForTimeout(1000);
      await page.screenshot({
        path: 'docs/screenshots/08-modal-share.png',
        fullPage: false,
      });
      await page.keyboard.press('Escape');
      await page.waitForTimeout(500);
    }

    // 8. Immersive Fullscreen Mode
    await page.goto('/#cheer', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1000);
    const fullscreenBtn = page.locator('[data-insightflare-event="fullscreen_toggle"]').first();
    if (await fullscreenBtn.isVisible()) {
      await fullscreenBtn.click();
      // Wait for header to auto-hide
      await page.waitForTimeout(4000);
      await page.screenshot({
        path: 'docs/screenshots/09-fullscreen-immersive.png',
        fullPage: false,
      });
      await page.keyboard.press('Escape');
      await page.waitForTimeout(500);
    }
  });

  // Mobile Viewport
  test('capture mobile responsive screenshot', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 }); // iPhone 14/15 size
    await page.goto('/', { waitUntil: 'networkidle' });
    await page.waitForTimeout(1500);

    await page.screenshot({
      path: 'docs/screenshots/10-mobile-view.png',
      fullPage: false,
    });
  });
});
